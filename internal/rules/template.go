package rules

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"
)

type AssessmentTargets struct {
	Enterprises []string
	Orgs        []string
	Repos       []string
}

// GenerateAssessmentTemplate creates a policy-config YAML skeleton containing
// every assessment-marked rule for the supplied targets. Values are blank by
// design; the result must be completed before LoadConfig will accept it.
func GenerateAssessmentTemplate(rs *Ruleset, targets AssessmentTargets, asOf string, maxAgeDays int) ([]byte, error) {
	if rs == nil {
		return nil, fmt.Errorf("ruleset is required")
	}
	if _, err := time.Parse("2006-01-02", asOf); err != nil {
		return nil, fmt.Errorf("as-of date must be YYYY-MM-DD")
	}
	if maxAgeDays <= 0 {
		return nil, fmt.Errorf("max assessment age must be positive")
	}
	enterprises, err := normalizeTargets(targets.Enterprises)
	if err != nil {
		return nil, fmt.Errorf("enterprise target: %w", err)
	}
	orgs, err := normalizeTargets(targets.Orgs)
	if err != nil {
		return nil, fmt.Errorf("org target: %w", err)
	}
	repos, err := normalizeTargets(targets.Repos)
	if err != nil {
		return nil, fmt.Errorf("repo target: %w", err)
	}
	if len(enterprises)+len(orgs)+len(repos) == 0 {
		return nil, fmt.Errorf("at least one enterprise, org, or repo target is required")
	}

	assessmentRules := map[Scope][]Rule{}
	for _, rule := range rs.Rules {
		if rule.Assessment {
			assessmentRules[rule.Scope] = append(assessmentRules[rule.Scope], rule)
		}
	}
	if len(assessmentRules) == 0 {
		return nil, fmt.Errorf("ruleset has no assessment-marked rules")
	}

	assessment := AssessmentConfig{
		AsOf: asOf, MaxAgeDays: maxAgeDays,
		Enterprises: assessmentEntries(enterprises, assessmentRules[ScopeEnterprise]),
		Orgs:        assessmentEntries(orgs, assessmentRules[ScopeOrg]),
		Repos:       assessmentEntries(repos, assessmentRules[ScopeRepo]),
	}
	template := struct {
		Assessments AssessmentConfig `yaml:"assessments"`
	}{Assessments: assessment}

	body, err := yaml.Marshal(template)
	if err != nil {
		return nil, fmt.Errorf("marshal assessment template: %w", err)
	}
	var out bytes.Buffer
	out.WriteString("# Generated by `postura config template`. Fill every blank assessment or remove entries you do not use.\n")
	out.WriteString("# Answer each `question` in `evidence`; `title` and `question` are guidance only and do not affect scoring.\n")
	out.WriteString("# Valid status values: compliant, partial, non_compliant, not_applicable.\n")
	out.WriteString("# Evidence, reviewed_at (YYYY-MM-DD), and reviewed_by are required.\n")
	out.Write(body)
	return out.Bytes(), nil
}

func normalizeTargets(targets []string) ([]string, error) {
	seen := map[string]bool{}
	out := make([]string, 0, len(targets))
	for _, target := range targets {
		target = strings.TrimSpace(target)
		if target == "" {
			return nil, fmt.Errorf("target cannot be empty")
		}
		if !seen[target] {
			seen[target] = true
			out = append(out, target)
		}
	}
	sort.Strings(out)
	return out, nil
}

func assessmentEntries(targets []string, rules []Rule) map[string]map[string]AssessmentInput {
	if len(targets) == 0 || len(rules) == 0 {
		return map[string]map[string]AssessmentInput{}
	}
	out := make(map[string]map[string]AssessmentInput, len(targets))
	for _, target := range targets {
		entries := make(map[string]AssessmentInput, len(rules))
		for _, rule := range rules {
			entries[rule.ID] = AssessmentInput{Title: rule.Title, Question: rule.Question}
		}
		out[target] = entries
	}
	return out
}
